DUMP_DIR = RESULTS_DIR / "dump"


def latest_ok(ds, cell, seed):
    last = None
    if RESULTS.exists():
        for line in RESULTS.read_text().splitlines():
            r = json.loads(line)
            if (r["dataset"], r["cell"], r["seed"]) == (ds, cell, seed) and not r.get("error"):
                last = r
    return last


def dump_path(ds, cell, seed):
    return DUMP_DIR / f"{ds}_{cell}_seed{seed}.jsonl"


def cmd_analyze(args):
    """Reload the saved checkpoint of each (dataset, cell, seed) and dump per-sample test predictions."""
    for ds, cell, seed in select(args):
        r = latest_ok(ds, cell, seed)
        if not (r and M.CELLS[cell]["ckpt"]):
            print(f"-- {ds} {cell} seed={seed}: no finished ckpt run, skipped")
            continue
        out = dump_path(ds, cell, seed)
        if out.exists() and not args.force:
            print(f"-- {out.name} exists")
            continue
        ckpt = ROOT / "save" / f"{r['run_id']}_{r['stamp']}.pth"
        opt = gen_config(cell, ds)
        opt["dump_path"] = str(out)
        opt["log_name"] = f"analyze/{r['run_id']}"
        run_dir = RUN_CFG_DIR / "analyze"
        run_dir.mkdir(parents=True, exist_ok=True)
        cfg = run_dir / f"{r['run_id']}.yaml"
        cfg.write_text(yaml.safe_dump(opt, sort_keys=False))
        cmd = [sys.executable, "run_crslab.py", "-c", str(cfg.relative_to(ROOT)), "-g", args.gpu,
               "-s", str(seed), "--rec_eval_from", str(ckpt)] + M.CELLS[cell]["cli"]
        print("==>", " ".join(cmd), flush=True)
        subprocess.run(cmd, cwd=ROOT, check=True, stdout=subprocess.DEVNULL)


def load_dump(ds, cell):
    """All seeds of a cell: (headers, rows) with rows tagged by seed."""
    heads, rows = [], []
    for f in sorted(DUMP_DIR.glob(f"{ds}_{cell}_seed*.jsonl")):
        lines = f.read_text().splitlines()
        heads.append(json.loads(lines[0]))
        seed = int(f.stem.rsplit("seed", 1)[1])
        rows += [{**json.loads(l), "seed": seed} for l in lines[1:]]
    return heads, rows


def recall_at(rows, k):
    return sum(r["rank"] <= k for r in rows) / max(1, len(rows))


def bucket(v, edges):
    for e in edges:
        if v <= e:
            return str(e)
    return f">{edges[-1]}"


def mean_attn(rows):
    out = []
    for lo, hi in ((0, 3), (3, 6), (6, 7)):
        vals = [sum(r["attn"][lo:hi]) for r in rows if r["attn"][0] == r["attn"][0]]  # skip NaN
        out.append(sum(vals) / len(vals) if vals else float("nan"))
    return out


def tail_ids(ds):
    p = ROOT / "data" / "collective" / ds / "tail_items.json"
    return set(json.load(open(p))) if p.exists() else set()


def cmd_report(args):
    exps = set(args.exp or [])
    out = []
    for ds in args.dataset or list(M.DATASETS):
        tails = tail_ids(ds)
        if "RQ3" in exps:  # coverage@k over the test lists + long-tail ratio of the top-10
            out += [f"## RQ3 {ds}", "", "| model | C@5 | C@10 | C@15 | C@20 | LT@10 |", "|---|---|---|---|---|---|"]
            for cell in ("hycorec_repro", "full"):
                _, rows = load_dump(ds, cell)
                if not rows:
                    continue
                cov = [len({i for r in rows for i in r["top20"][:k]}) for k in (5, 10, 15, 20)]
                tot = sum(10 for r in rows)
                lt = sum(i in tails for r in rows for i in r["top20"][:10]) / max(1, tot)
                out.append(f"| {cell} | " + " | ".join(str(c) for c in cov) + f" | {lt:.4f} |")
            out += ["", "C@k = number of distinct items in >=1 top-k list over the test set (divide by |V_I| for a ratio); "
                    "LT@10 = share of top-10 slots held by tail items (outside the head holding 80% of train mentions).", ""]
        if "RQ6" in exps:  # target is tail, HyCoRec misses top-5, CPG hits top-5
            _, a = load_dump(ds, "hycorec_repro")
            _, b = load_dump(ds, "full")
            key = lambda r: (r["seed"], r["conv_id"], r["n_turn"], r["target"])
            base = {key(r): r for r in a}
            cases = [{"conv_id": r["conv_id"], "n_turn": r["n_turn"], "target": r["target"],
                      "rank_hycorec": base[key(r)]["rank"], "rank_cpg": r["rank"],
                      "top5_hycorec": base[key(r)]["top20"][:5], "top5_cpg": r["top20"][:5]}
                     for r in b if key(r) in base and r["target"] in tails and base[key(r)]["rank"] > 5 and r["rank"] <= 5]
            (RESULTS_DIR / f"rq6_cases_{ds}.json").write_text(json.dumps(cases, indent=1))
            out += [f"## RQ6 {ds}: {len(cases)} candidate cases -> results/cpg/rq6_cases_{ds}.json "
                    "(ids are entity ids; map with entity2id.json, pick a readable conversation by hand)", ""]
        if "extra-S4" in exps:
            out += [f"## extra-S4 cost {ds}", "", "| cell | R@10 | params (M) | infer ms/sample | train s/epoch |", "|---|---|---|---|---|"]
            for cell in ("lad_A3", "lad_A4", "full"):
                heads, rows = load_dump(ds, cell)
                if not rows:
                    continue
                r = latest_ok(ds, cell, int(sorted({x['seed'] for x in rows})[0]))
                te = epoch_seconds(ROOT / r["log_path"]) if r else None
                out.append(f"| {cell} | {recall_at(rows, 10):.4f} | {heads[0]['params_M']:.2f} | "
                           f"{heads[0]['infer_ms_per_sample']:.2f} | {te if te is None else round(te, 1)} |")
            out.append("")
        if "extra-S6" in exps:
            _, f = load_dump(ds, "full")
            _, h = load_dump(ds, "hycorec_repro")
            out += [f"## extra-S6 {ds}: by number of turns so far", "",
                    "| turns | n | R@10 HyCoRec | R@10 CPG | attn C | attn P | attn G |", "|---|---|---|---|---|---|---|"]
            edges = [1, 2, 3, 5, 8]
            for e in [str(x) for x in edges] + [f">{edges[-1]}"]:
                fb = [r for r in f if bucket(r["n_turn"], edges) == e]
                hb = [r for r in h if bucket(r["n_turn"], edges) == e]
                if fb:
                    c, p, g = mean_attn(fb)
                    out.append(f"| {e} | {len(fb)} | {recall_at(hb, 10):.4f} | {recall_at(fb, 10):.4f} | {c:.3f} | {p:.3f} | {g:.3f} |")
            out.append("")
        if "extra-S7" in exps:
            _, f = load_dump(ds, "full")
            _, h = load_dump(ds, "hycorec_repro")
            out += [f"## extra-S7 {ds}: by history sessions", "",
                    "| history | n | R@10 HyCoRec | R@10 CPG | attn C | attn P | attn G |", "|---|---|---|---|---|---|---|"]
            edges = [0, 1, 2]
            for e in [str(x) for x in edges] + [">2"]:
                fb = [r for r in f if bucket(r["n_hist"], edges) == e]
                hb = [r for r in h if bucket(r["n_hist"], edges) == e]
                if fb:
                    c, p, g = mean_attn(fb)
                    out.append(f"| {e} | {len(fb)} | {recall_at(hb, 10):.4f} | {recall_at(fb, 10):.4f} | {c:.3f} | {p:.3f} | {g:.3f} |")
            out.append("")
    text = "\n".join(out)
    (RESULTS_DIR / f"report_{'_'.join(sorted(exps))}.md").write_text(text)
    print(text)


def epoch_seconds(log: Path):
    """Mean seconds between consecutive '[Recommendation epoch N]' lines of a run log."""
    ts = []
    for line in log.read_text(errors="replace").splitlines():
        if "[Recommendation epoch" in line:
            ts.append(time.mktime(time.strptime(line[:19], "%Y-%m-%d %H:%M:%S")))
    return (ts[-1] - ts[0]) / (len(ts) - 1) if len(ts) > 1 else None


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("gen").set_defaults(fn=cmd_gen)
    for name, fn in (("plan", cmd_plan), ("run", cmd_run), ("summarize", cmd_summarize),
                     ("analyze", cmd_analyze), ("report", cmd_report)):
        p = sub.add_parser(name)
        p.add_argument("--exp", nargs="*", help="RQ1 RQ4 RQ5 extra-S2 extra-S3 extra-S4 extra-S8 extra-S12")
        p.add_argument("--cells", nargs="*")
        p.add_argument("--dataset", nargs="*", choices=list(M.DATASETS))
        p.add_argument("--seeds", nargs="*", type=int, default=None, help="default: per-cell (3 seeds; RQ5 one)")
        p.add_argument("--prio", type=int, help="only cells with priority <= this")
        if name in ("run", "analyze"):
            p.add_argument("--gpu", default="0")
        if name == "analyze":
            p.add_argument("--force", action="store_true")
        if name == "run":
            p.add_argument("--ddp", action="store_true", help="ONE run over all --gpu ids (torch.distributed)")
            p.add_argument("--parallel", action="store_true",
                           help="--gpu 0,1,2,3 = four independent single-GPU runs at a time (usual choice)")
            p.add_argument("--rec-bs", type=int, help="override rec batch size (global)")
            p.add_argument("--conv-bs", type=int, help="override conv batch size (global)")
            p.add_argument("--force", action="store_true")
            p.add_argument("--smoke", action="store_true", help="1%% data, 1 epoch, results not recorded")
            p.add_argument("--timeout-hours", type=float, default=None)
        p.set_defaults(fn=fn)
    args = ap.parse_args()
    args.fn(args)


if __name__ == "__main__":
    main()
