#!/usr/bin/env python3
"""Driver for the CPG-Hypergraph paper experiments (docs/CPG-Hypergraph_Experiment.md).

Kept separate from the old ablation ladder (run_ablation.py): own configs
(config/crs/cpg/), own results (results/cpg/), fresh log/ tree
(log/<stamp>/cpg_<dataset>_<cell>_seed<seed>.log) and checkpoints (save/cpg_*.pth).

    python scripts/run_cpg.py gen                                   # (re)write all yaml from cpg_manifest.py
    python scripts/run_cpg.py plan --exp S1 S2                      # list runs, status, what is missing
    python scripts/run_cpg.py run --exp S1 --dataset htgredial --gpu 0
    python scripts/run_cpg.py run --cells full wo_C --seeds 3407    # explicit cells
    python scripts/run_cpg.py run --prio 1 --gpu 0,1,2,3 --parallel # 4 runs at a time, one per GPU
    python scripts/run_cpg.py run --exp RQ1 --gpu 0,1 --ddp         # ONE run split over 2 GPUs
    python scripts/run_cpg.py run --exp S3 --smoke --gpu 0          # 1% data, 1 epoch, nothing recorded: checks a cell starts
    python scripts/run_cpg.py analyze --cells full hycorec_repro    # test-set dump from the saved ckpt (S4/S6/S7/S11)
    python scripts/run_cpg.py report --exp S4 S6 S7 S11             # tables from the dumps
    python scripts/run_cpg.py summarize --exp S2                    # mean +- std over seeds -> results/cpg/summary_<exp>.md

Cells whose collective / review index is not built yet are listed by ``plan`` and skipped by ``run``
(scripts/build_cpg_data.sh builds them). S10 is a separate script: scripts/cpg_s10.py.
"""
from __future__ import annotations

import argparse
import json
import statistics
import subprocess
import sys
import time
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import cpg_manifest as M  # noqa: E402
import run_ablation as RA  # noqa: E402  (reuse the log parser / process handling)

ROOT = RA.ROOT
CFG_DIR = ROOT / "config" / "crs" / "cpg"
RUN_CFG_DIR = CFG_DIR / "_runs"
RESULTS_DIR = ROOT / "results" / "cpg"
RESULTS = RESULTS_DIR / "results.jsonl"

SUMMARY_COLS = ["recall@10", "recall@50", "mrr@10", "mrr@50", "ndcg@10", "ndcg@50", "tail_recall@10", "tail_recall@50"]
CONV_COLS = ["dist@2", "dist@3", "dist@4"]


def overrides(cell: str, dataset: str) -> dict:
    over = M.CELLS[cell]["over"]
    return over(M.DATASETS[dataset][1]) if callable(over) else over


def status(cell: str, dataset: str) -> str:
    """needs_data cells flip to ready once every path they point at exists."""
    st = M.CELLS[cell]["status"]
    if st == "needs_data":
        paths = [v for k, v in overrides(cell, dataset).items() if k in ("collective_path", "review_index_path") and v]
        if paths and all((ROOT / p).exists() for p in paths):
            return "ready"
    return st


def gen_config(cell: str, dataset: str) -> dict:
    base = yaml.safe_load((ROOT / M.DATASETS[dataset][0]).read_text())
    opt = {**base, **overrides(cell, dataset)}
    opt["rec_only"] = bool(M.CELLS[cell]["rec_only"])
    return opt


def cfg_dir(cell: str, dataset: str) -> Path:
    extra = M.CELLS[cell]["exp"].startswith("extra")
    return CFG_DIR / dataset / ("extra" if extra else "")


def applicable(cell: str, dataset: str) -> bool:
    ds = M.CELLS[cell]["datasets"]
    return ds is None or dataset in ds


def cmd_gen(args):
    n = 0
    for dataset in M.DATASETS:
        for cell, spec in M.CELLS.items():
            if not applicable(cell, dataset):
                continue
            out = cfg_dir(cell, dataset)
            out.mkdir(parents=True, exist_ok=True)
            header = (f"# {spec['exp']} / {cell} ({dataset}) -- GENERATED by scripts/run_cpg.py gen from "
                      f"scripts/cpg_manifest.py; do not edit by hand.\n# status={spec['status']}"
                      + (f" -- {spec['note']}" if spec["note"] else "") + "\n")
            (out / f"{cell}.yaml").write_text(header + yaml.safe_dump(gen_config(cell, dataset), sort_keys=False))
            n += 1
    print(f"wrote {n} configs under {CFG_DIR.relative_to(ROOT)}/")


def select(args) -> list[tuple[str, str, int]]:
    datasets = args.dataset or list(M.DATASETS)
    names = args.cells or [c for c, s in M.CELLS.items() if (not args.exp or s["exp"] in args.exp)]
    plan = []
    for cell in names:
        if cell not in M.CELLS:
            sys.exit(f"unknown cell {cell!r}")
        if args.prio and M.CELLS[cell]["prio"] > args.prio:
            continue
        for ds in datasets:
            if applicable(cell, ds):
                for seed in args.seeds or M.CELLS[cell]["seeds"] or M.SEEDS:
                    plan.append((ds, cell, seed))
    return plan


def done(ds: str, cell: str, seed: int) -> bool:
    if not RESULTS.exists():
        return False
    for line in RESULTS.read_text().splitlines():
        r = json.loads(line)
        if (r["dataset"], r["cell"], r["seed"]) == (ds, cell, seed) and not r.get("error"):
            return True
    return False


def cmd_plan(args):
    plan = select(args)
    by_status: dict[str, int] = {}
    for ds, cell, seed in plan:
        spec = M.CELLS[cell]
        st = status(cell, ds)
        by_status[st] = by_status.get(st, 0) + 1
        flag = "done" if done(ds, cell, seed) else st
        extra = f"  <- {spec['need']}" if spec["need"] and st != "ready" else ""
        print(f"{spec['exp']:7s} {ds:10s} {cell:14s} seed={seed:<5d} prio={spec['prio']} "
              f"{'rec+conv' if not spec['rec_only'] else 'rec    '} {flag}{extra}")
    print(f"\n{len(plan)} runs: {by_status}")


def run_one(ds: str, cell: str, seed: int, gpu: str, ddp: bool, stamp: str, timeout_h: float | None,
            smoke: bool = False, rec_bs: int | None = None, conv_bs: int | None = None) -> dict:
    spec = M.CELLS[cell]
    rid = f"cpg_{ds}_{cell}_seed{seed}"
    opt = gen_config(cell, ds)
    if rec_bs:  # GPU-memory fit; batch_size is global (split across ranks under --ddp)
        opt["rec"]["batch_size"] = rec_bs
    if conv_bs:
        opt["conv"]["batch_size"] = conv_bs
    if smoke:  # pipeline check only: 1% of the data, one epoch, never recorded
        opt["scale"] = 0.01
        opt["rec"].update(epoch=1, early_stop=False)
        opt["conv"].update(epoch=1, early_stop=False)
    opt["log_name"] = f"{stamp}/{rid}"
    opt["model_file"] = f"{rid}_{stamp}.pth"
    run_dir = RUN_CFG_DIR / stamp
    run_dir.mkdir(parents=True, exist_ok=True)
    cfg = run_dir / f"{rid}.yaml"
    cfg.write_text(yaml.safe_dump(opt, sort_keys=False))

    log_dir = ROOT / "log" / stamp
    log_dir.mkdir(parents=True, exist_ok=True)
    py = [sys.executable]
    n_gpu = len(gpu.split(","))
    if ddp and gpu != "-1" and n_gpu > 1:
        py += ["-m", "torch.distributed.run", "--standalone", f"--nproc_per_node={n_gpu}"]
    cmd = py + ["run_crslab.py", "-c", str(cfg.relative_to(ROOT)), "-g", gpu, "-s", str(seed)]
    if spec["ckpt"] and not smoke:
        cmd.append("-ss")
    cmd += spec["cli"]
    print(f"==> {rid}: {' '.join(cmd)}", flush=True)
    t0 = time.time()
    res = {"dataset": ds, "cell": cell, "exp": spec["exp"], "seed": seed, "stamp": stamp, "run_id": rid,
           "rec_only": spec["rec_only"], "cmd": " ".join(cmd)}
    try:
        with open(log_dir / f"{rid}.stderr", "w") as errf:
            proc = subprocess.run(cmd, cwd=ROOT, stderr=errf, stdout=subprocess.DEVNULL,
                                  timeout=timeout_h * 3600 if timeout_h else None)
        res["returncode"] = proc.returncode
    except subprocess.TimeoutExpired:
        res["returncode"], res["error"] = None, f"timed out after {timeout_h}h"
    res["launch_wall_seconds"] = time.time() - t0
    log_path = log_dir / f"{rid}.log"
    res.update(RA.parse_log(log_path))
    res["log_path"] = str(log_path.relative_to(ROOT))
    if res.get("returncode") not in (0, None):
        res["error"] = f"exit {res['returncode']}; see {rid}.stderr"
    elif res["rec_test"] is None or (not spec["rec_only"] and not res["reached_conv_test"]):
        res.setdefault("error", "run finished without the expected test report (see log/stderr)")
    print(f"<== {rid}: {'FAILED ' + res['error'] if res.get('error') else 'OK'} ({res['launch_wall_seconds']/60:.1f} min)",
          flush=True)
    return res


def cmd_run(args):
    plan = select(args)
    runnable = [(d, c, s) for d, c, s in plan if status(c, d) == "ready"]
    skipped = sorted({c for d, c, _ in plan if status(c, d) != "ready"})
    if skipped:
        print(f"!! skipping not-ready cells (see `plan`): {', '.join(skipped)}")
    todo = [(d, c, s) for d, c, s in runnable if args.force or not done(d, c, s)]
    n_done = len(runnable) - len(todo)
    if args.smoke:
        todo = list({(d, c): (d, c, s) for d, c, s in runnable}.values())  # one run per (dataset, cell)
    print(f"{len(todo)} runs to do ({n_done} already done)")
    if not RESULTS_DIR.exists():
        RESULTS_DIR.mkdir(parents=True)
    stamp = ("smoke-" if args.smoke else "") + time.strftime("%Y%m%d-%H%M%S")
    print(f"Logs: log/{stamp}/")
    import threading
    from concurrent.futures import ThreadPoolExecutor
    from queue import Queue

    lock = threading.Lock()
    gpus = Queue()
    if args.parallel:  # one single-GPU job per listed GPU, jobs pulled from a shared queue
        for g in args.gpu.split(","):
            gpus.put(g)
    else:
        gpus.put(args.gpu)

    def job(item):
        d, c, s = item
        g = gpus.get()
        try:
            res = run_one(d, c, s, g, args.ddp, stamp, args.timeout_hours, smoke=args.smoke,
                          rec_bs=args.rec_bs, conv_bs=args.conv_bs)
        finally:
            gpus.put(g)
        if not args.smoke:
            with lock, open(RESULTS, "a") as f:
                f.write(json.dumps(res) + "\n")

    with ThreadPoolExecutor(max_workers=gpus.qsize()) as ex:
        list(ex.map(job, todo))


def cmd_summarize(args):
    if not RESULTS.exists():
        sys.exit("no results yet")
    rows = [json.loads(l) for l in RESULTS.read_text().splitlines()]
    for r in rows:  # runs flagged only because an older parser missed the report: re-read their log
        if str(r.get("error", "")).startswith("run finished without") and r.get("log_path"):
            r.update(RA.parse_log(ROOT / r["log_path"]))
            if r["rec_test"] is not None and (r["rec_only"] or r["reached_conv_test"]):
                r.pop("error")
    rows = [r for r in rows if not r.get("error") and (not args.exp or r["exp"] in args.exp)]
    groups: dict[tuple, list] = {}
    for r in rows:
        groups.setdefault((r["dataset"], r["exp"], r["cell"]), []).append(r)

    def ms(vals):
        return f"{statistics.mean(vals):.4f} ± {statistics.stdev(vals):.4f}" if len(vals) > 1 else f"{vals[0]:.4f}"

    out = []
    for ds in M.DATASETS:
        sel = {k: v for k, v in groups.items() if k[0] == ds}
        if not sel:
            continue
        has_conv = any(not r["rec_only"] for v in sel.values() for r in v)
        cols = SUMMARY_COLS + (CONV_COLS if has_conv else [])
        out += [f"## {ds}", "", "| exp | cell | n | " + " | ".join(cols) + " |", "|---|---|---|" + "---|" * len(cols)]
        for (_, exp, cell), rs in sorted(sel.items(), key=lambda kv: (kv[0][1], kv[0][2])):
            cells = []
            for c in cols:
                src = "conv_test" if c in CONV_COLS else "rec_test"
                vals = [r[src][c] for r in rs if r.get(src) and c in r[src]]
                cells.append(ms(vals) if vals else "-")
            out.append(f"| {exp} | {cell} | {len(rs)} | " + " | ".join(cells) + " |")
        out.append("")
    text = "\n".join(out)
    tag = "_".join(args.exp) if args.exp else "all"
    (RESULTS_DIR / f"summary_{tag}.md").write_text(text)
    print(text)


